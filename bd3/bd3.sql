CREATE DATABASE IF NOT EXISTS Магазин;
USE Магазин;

-- создание таблицы покупатели
CREATE TABLE IF NOT EXISTS Покупатели (
    ID_покупателя INT AUTO_INCREMENT PRIMARY KEY,
    ФИО VARCHAR(255) NOT NULL,
    Телефон VARCHAR(20),
    Адрес VARCHAR(500),
    Email VARCHAR(100)
);

-- создание таблицы товары
CREATE TABLE IF NOT EXISTS Товары (
    ID_товара INT AUTO_INCREMENT PRIMARY KEY,
    Название_товара VARCHAR(255) NOT NULL,
    Цена DECIMAL(10, 2) NOT NULL CHECK (Цена > 0),
    Количество_на_складе INT NOT NULL DEFAULT 0 CHECK (Количество_на_складе >= 0),
    Категория VARCHAR(100),
    Описание TEXT
);

-- создание таблицы заказы
CREATE TABLE IF NOT EXISTS Заказы (
    ID_заказа INT AUTO_INCREMENT PRIMARY KEY,
    ID_покупателя INT NOT NULL,
    Дата_заказа DATE NOT NULL DEFAULT (CURRENT_DATE),
    Статус VARCHAR(50) DEFAULT 'Обрабатывается',
    FOREIGN KEY (ID_покупателя) REFERENCES Покупатели(ID_покупателя) ON DELETE CASCADE
);

-- создание таблицы состав заказа
CREATE TABLE IF NOT EXISTS Состав_заказа (
    ID_заказа INT,
    ID_товара INT,
    Количество INT NOT NULL CHECK (Количество > 0),
    Цена_на_момент_покупки DECIMAL(10, 2) NOT NULL,
    PRIMARY KEY (ID_заказа, ID_товара),
    FOREIGN KEY (ID_заказа) REFERENCES Заказы(ID_заказа) ON DELETE CASCADE,
    FOREIGN KEY (ID_товара) REFERENCES Товары(ID_товара) ON DELETE CASCADE
);

-- создание индекса для ускорения поиска по названию товара
CREATE INDEX idx_товар_название ON Товары(Название_товара);

